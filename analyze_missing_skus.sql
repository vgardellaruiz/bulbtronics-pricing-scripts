-- Summary by status
SELECT 
    CASE 
        WHEN p.PROD_SKU IS NULL THEN 'NOT_IN_DB'
        WHEN p.PROD_LOCATION <> 1 THEN 'NOT_WH1'
        WHEN p.PROD_STATUS NOT IN ('N', 'D') THEN 'INACTIVE_STATUS'
        WHEN p.PROD_STATUS = 'D' AND (p.RECD - p.USED) <= 0 THEN 'NO_INVENTORY'
        WHEN p.CATEGORY = 'NONE' THEN 'NONE_CATEGORY'
        WHEN p.PROD_SKU_CLASS <> 'N' THEN 'SPECIAL_CLASS'
        WHEN p.REF_COST IS NULL THEN 'NO_REF_COST'
        ELSE 'SHOULD_BE_INCLUDED'
    END AS Status,
    COUNT(*) AS SKU_Count
FROM TargetSKUs ts
LEFT JOIN dbo.Prod p WITH (NOLOCK) 
    ON LTRIM(RTRIM(p.PROD_SKU)) = ts.SKU
    AND p.PROD_LOCATION = 1
GROUP BY 
    CASE 
        WHEN p.PROD_SKU IS NULL THEN 'NOT_IN_DB'
        WHEN p.PROD_LOCATION <> 1 THEN 'NOT_WH1'
        WHEN p.PROD_STATUS NOT IN ('N', 'D') THEN 'INACTIVE_STATUS'
        WHEN p.PROD_STATUS = 'D' AND (p.RECD - p.USED) <= 0 THEN 'NO_INVENTORY'
        WHEN p.CATEGORY = 'NONE' THEN 'NONE_CATEGORY'
        WHEN p.PROD_SKU_CLASS <> 'N' THEN 'SPECIAL_CLASS'
        WHEN p.REF_COST IS NULL THEN 'NO_REF_COST'
        ELSE 'SHOULD_BE_INCLUDED'
    END
ORDER BY SKU_Count DESC;

-- Category distribution for products that SHOULD be included
SELECT 
    LTRIM(RTRIM(p.CATEGORY)) AS CATEGORY,
    COUNT(*) AS SKU_Count
FROM TargetSKUs ts
INNER JOIN dbo.Prod p WITH (NOLOCK) 
    ON LTRIM(RTRIM(p.PROD_SKU)) = ts.SKU
WHERE p.PROD_LOCATION = 1
    AND (p.PROD_STATUS = 'N' OR (p.PROD_STATUS = 'D' AND p.RECD - p.USED > 0))
    AND p.CATEGORY <> 'NONE'
    AND p.PROD_SKU_CLASS = 'N'
    AND p.REF_COST IS NOT NULL
GROUP BY LTRIM(RTRIM(p.CATEGORY))
ORDER BY SKU_Count DESC;
